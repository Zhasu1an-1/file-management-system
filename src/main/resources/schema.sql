CREATE TABLE IF NOT EXISTS users (
    username VARCHAR(32) PRIMARY KEY,
    display_name VARCHAR(80) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('OWNER', 'VIEWER'))
);

CREATE TABLE IF NOT EXISTS folders (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    owner_username VARCHAR(32) NOT NULL REFERENCES users(username)
);
CREATE UNIQUE INDEX IF NOT EXISTS folders_owner_name ON folders (owner_username, lower(name));

CREATE TABLE IF NOT EXISTS files (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    file_type VARCHAR(16) NOT NULL,
    size_bytes INTEGER NOT NULL CHECK (size_bytes > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    owner_username VARCHAR(32) NOT NULL REFERENCES users(username),
    folder_id UUID REFERENCES folders(id),
    storage_type VARCHAR(16) NOT NULL CHECK (storage_type IN ('LOCAL', 'DATABASE'))
);
CREATE UNIQUE INDEX IF NOT EXISTS files_owner_name ON files (owner_username, lower(name));
CREATE INDEX IF NOT EXISTS files_folder ON files (folder_id);

CREATE TABLE IF NOT EXISTS file_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id UUID NOT NULL REFERENCES files(id) ON DELETE CASCADE,
    viewer_username VARCHAR(32) NOT NULL REFERENCES users(username),
    UNIQUE (file_id, viewer_username)
);

CREATE TABLE IF NOT EXISTS file_contents (
    file_id UUID PRIMARY KEY REFERENCES files(id) ON DELETE CASCADE,
    content BYTEA NOT NULL
);
